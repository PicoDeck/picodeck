#!/usr/bin/env python3
"""Pack the files the firmware owns on the SD card into a generated C source.

The App Store, System Update and the shared Lua libraries belong to the firmware
(issue #92): src/os/card_files.c writes them to the card at boot whenever the card's
copy is missing, a different size, or from another bundle. This script is the one
list of what is bundled (BUNDLE) and turns those files into byte arrays, a path table
and a bundle id: the SHA-256 of every path and its contents, so any change to any
bundled file gives a new id and the next boot rewrites the card.

    python3 tools/card_files.py --repo <repo root> --out <generated .c>

The output is rewritten only when its text changes, so an unchanged bundle does not
rebuild the firmware. Tests: tests/unit/test_card_files_gen.py.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

# (repo path, card path): a directory is bundled whole, recursively.
BUNDLE = [
    ("apps/store", "/apps/store"),
    ("apps/updater", "/apps/updater"),
    ("system/lib", "/system/lib"),
    # Spleen is BSD 2-Clause: copies on a card ship the licence beside the font.
    ("sdk/fonts/spleen/LICENSE", "/system/lib/fonts/spleen-LICENSE"),
]

# What the firmware owns on the card: card_files.c writes and deletes only below these.
ROOTS = ("/apps/store/", "/apps/updater/", "/system/lib/")

# SD_ATOMIC_PATH_MAX (src/os/sd_atomic.h) is 192 with the ".tmp"/".bak" suffix.
MAX_PATH = 150


def _fail(reason: str):
    raise SystemExit(f"card_files: {reason}")


def _check(card: str) -> str:
    if not card.isascii():
        _fail(f"{card!r}: card paths must be ASCII")
    if len(card) > MAX_PATH:
        _fail(f"{card}: longer than {MAX_PATH} characters")
    if not any(card.startswith(r) for r in ROOTS):
        _fail(f"{card}: not under {', '.join(ROOTS)}")
    return card


def collect(repo: Path) -> list[tuple[str, bytes]]:
    """Every bundled file as (card path, contents), sorted by card path."""
    files = []
    for rel, dst in BUNDLE:
        src = repo / rel
        if src.is_file():
            files.append((_check(dst), src.read_bytes()))
        elif src.is_dir():
            for p in sorted(src.rglob("*")):
                parts = p.relative_to(src).parts
                if any(part.startswith(".") for part in parts) or not p.is_file():
                    continue
                files.append((_check(dst + "/" + "/".join(parts)), p.read_bytes()))
        else:
            _fail(f"{rel}: missing from {repo}")
    files.sort(key=lambda f: f[0])
    paths = [p for p, _ in files]
    if len(set(paths)) != len(paths):
        _fail("two sources map to the same card path")
    return files


def bundle_id(files: list[tuple[str, bytes]]) -> str:
    h = hashlib.sha256()
    for path, data in files:
        h.update(path.encode("ascii") + b"\0" + len(data).to_bytes(8, "little") + data)
    return h.hexdigest()


def _array(name: str, data: bytes) -> str:
    if not data:  # C has no zero-length arrays; the table's length says 0
        return f"static const uint8_t {name}[1] = {{0}};\n"
    rows = (", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16))
    return f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


def render_c(files: list[tuple[str, bytes]], bid: str) -> str:
    out = ["// Generated by tools/card_files.py: do not edit. The files the firmware\n"
           "// owns on the SD card (src/os/card_files.c).\n",
           '#include "card_files.h"\n\n']
    for i, (_, data) in enumerate(files):
        out.append(_array(f"f{i}", data))
    out.append("\nstatic const card_file_t s_files[] = {\n")
    for i, (path, data) in enumerate(files):
        out.append(f'    {{"{path}", f{i}, {len(data)}u}},\n')
    out.append("};\n\nstatic const char *const s_roots[] = {\n")
    out.extend(f'    "{r}",\n' for r in ROOTS)
    out.append("};\n\n")
    out.append("const card_bundle_t g_card_bundle = {\n"
               f'    "{bid}",\n'
               f"    s_files,\n    {len(files)},\n"
               f"    s_roots,\n    {len(ROOTS)},\n}};\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    files = collect(args.repo)
    bid = bundle_id(files)
    text = render_c(files, bid)
    if not args.out.exists() or args.out.read_text() != text:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
    print(f"card_files: {len(files)} files, {sum(len(d) for _, d in files)} bytes, id {bid[:8]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
