T.case("new_and_sizes", function()
    local g = CG.new(10, 5, 0)
    local c, r = g:getSize(); T.eq(c, 10); T.eq(r, 5)
    local cw, ch = g:getCellSize(); T.eq(cw, 6); T.eq(ch, 8)
    cw, ch = CG.new(80, 40, nil, 4, 4):getCellSize(); T.eq(cw, 4); T.eq(ch, 4)
    cw, ch = CG.new(4, 2, 0, 8, 12):getCellSize(); T.eq(cw, 8); T.eq(ch, 12)
    cw, ch = CG.new(4, 2, 1):getCellSize(); T.eq(cw, 8); T.eq(ch, 12)
    T.eq(CG.new(9.6, 2.2, 0):getSize(), 10)   -- quantities round
end)

T.case("new_errors", function()
