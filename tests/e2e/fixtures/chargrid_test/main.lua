T.case("setRow_forms", function()
    local g = CG.new(6, 2, 0)
    g:setRow(0, "abc", { 1, 2, 3 }, 7)
    local gl, fg, bg = g:getRow(0, 0, 4)
    T.eq(gl, "abc\0"); T.eq(fg, "\1\2\3\15"); T.eq(bg, "\7\7\7\0")
    g:setRow(1, nil, 9, nil, 2)
    gl, fg = g:getRow(1)
    T.eq(fg, "\15\15\9\9\9\9"); T.eq(gl, "\0\0\0\0\0\0")
    g:setRow(0, "XYZ", nil, nil, -1)
    T.eq((g:getRow(0, 0, 3)), "YZc")
    g:setRow(0, "123", nil, nil, 5)
    T.eq((g:getRow(0, 4, 2)), "\0" .. "1")
    T.eq((g:getRow(0, 4, 5)), "\0" .. "1")
    T.eq((g:getRow(5)), "")
    T.raises(function() g:setRow(0, "ab", { 1, 2, 3 }) end, "different lengths")
    T.raises(function() g:setRow(0, { 1, 256 }) end, "glyphs entry 2 must be an integer 0%-255")
    T.raises(function() g:setRow(0, { 1, 2.5 }) end, "glyphs entry 2 must be an integer 0%-255")
