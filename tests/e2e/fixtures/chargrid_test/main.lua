T.case("ramps_and_shadeRow", function()
    local g = CG.new(4, 2, 0)
    T.raises(function() g:shadeRow(0, { 0.5 }) end, "no ramp")
    g:setRamp(" .:#")
    g:shadeRow(0, { 0, 0.34, 0.67, 1 })
    T.eq((g:getRow(0)), " .:#")
    g:setRamp("·•●")
    g:shadeRow(1, { 0, 0.5, 1, 0 / 0 })
    T.eq((g:getRow(1)), char(CG.DOT1, CG.DOT2, CG.DOT3, CG.DOT1))
    T.raises(function() g:shadeRow(0, nil, { 1 }) end, "no colour ramp")
    g:setColorRamp({ 10, 11 })
    g:shadeRow(0, { 0, 1, 0, 1 })
    local gl, fg = g:getRow(0)
    T.eq(gl, char(CG.DOT1, CG.DOT3, CG.DOT1, CG.DOT3)); T.eq(fg, "\10\11\10\11")
    g:shadeRow(0, nil, { 1, 1, 0, 0 })
    gl, fg = g:getRow(0)
    T.eq(gl, char(CG.DOT1, CG.DOT3, CG.DOT1, CG.DOT3)); T.eq(fg, "\11\11\10\10")
    T.raises(function() g:shadeRow(0, { 1 }, { 1, 2 }) end, "different lengths")
    T.raises(function() g:shadeRow(0) end, "levels or tones")
    T.raises(function() g:setRamp("") end, "1%-256")
    T.raises(function() g:setColorRamp({ 300 }) end, "0%-255")
    local d = CG.new(4, 4, 0)
    d:setRamp(" #", true)
    for y = 0, 3 do d:shadeRow(y, { 0.5, 0.5, 0.5, 0.5 }) end
    local on = 0
    for y = 0, 3 do on = on + select(2, d:getRow(y):gsub("#", "")) end
    T.eq(on, 8)
end)

