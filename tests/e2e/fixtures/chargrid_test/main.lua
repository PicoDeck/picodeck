    T.raises(function() CG.new(10, 5, nil, 4, 33) end, "cellH must be 1%-32")
    T.raises(function() CG.new(10, 5, 9) end, "font 9 is not loaded")
    T.raises(function() CG.new(10, 5, 1.5) end, "integer")
end)

T.case("set_get", function()
    local g = CG.new(4, 3, 0)
    g:set(1, 2, "A", 3, 4)
    local c, f, b = g:get(1, 2); T.eq(c, 65); T.eq(f, 3); T.eq(b, 4)
    g:set(1, 2, 66)
    c, f, b = g:get(1, 2); T.eq(c, 66); T.eq(f, 3); T.eq(b, 4)
    g:set(0, 0, "█"); T.eq((g:get(0, 0)), CG.SHADE4)
    g:set(0, 0, "é"); T.eq((g:get(0, 0)), 0xE9)
    g:set(9, 9, "A")
    c, f, b = g:get(9, 9); T.eq(c, 0); T.eq(f, 0); T.eq(b, 0)
    T.raises(function() g:set(0, 0, "ab") end, "one character")
    T.raises(function() g:set(0, 0, "") end, "one character")
    T.raises(function() g:set(0, 0, 256) end, "glyph must be 0%-255")
    T.raises(function() g:set(0, 0, 65, 1.5) end, "integer")
    T.raises(function() g:set(0, 0, 65, -1) end, "fg must be 0%-255")
end)

