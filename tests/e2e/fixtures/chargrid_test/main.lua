    T.eq(CG.TRI_UP, 24); T.eq(CG.TRI_LEFT, 27)
    T.eq(CG.BOX_SINGLE, 0); T.eq(CG.BOX_BLOCK, 1); T.eq(CG.BOX_ASCII, 2)
