T.case("rect tables: positional and named are the same", function()
    fresh()
    local s = S.new(solid(10, 10, RED))
    s:setBounds({ 1, 2, 3, 4 })
    local x, y, w, h = s:getBounds()
    T.eq(x, 1) T.eq(y, 2) T.eq(w, 3) T.eq(h, 4)
    s:setBounds({ x = 5, y = 6, w = 7, h = 8 })
    x, y, w, h = s:getBounds()
    T.eq(x, 5) T.eq(y, 6) T.eq(w, 7) T.eq(h, 8)
    s:setBounds(s:getBoundsRect())      -- the getter's table round-trips
    x, y, w, h = s:getBounds()
    T.eq(x, 5) T.eq(y, 6) T.eq(w, 7) T.eq(h, 8)
    s:setBounds({ 1, 2, 3, 4, x = 9 })  -- a named field wins, as in img:draw
    x = s:getBounds()
    T.eq(x, 9)
    s:setCollideRect({ 1, 2, 3, 4 })
    x, y, w, h = s:getCollideRect()
    T.eq(x, 1) T.eq(y, 2) T.eq(w, 3) T.eq(h, 4)
    s:moveTo(100, 100)
    T.eq(s:checkCollisions({ 101, 102 }), true)
    T.eq(s:checkCollisions({ x = 101, y = 102 }), true)
    s:add()
    T.eq(#S.querySpritesAtPoint({ 101, 102 }), 1)
    T.eq(#S.querySpritesInRect({ 100, 100, 5, 5 }), 1)
    T.eq(#S.querySpritesAlongLine({ 0, 102, 319, 102 }), 1)
    T.eq(#S.querySpriteInfoAlongLine({ 0, 102, 319, 102 }), 1)
    local e = S.addEmptyCollisionSprite({ 1, 2, 3, 4 })
    T.eq(e.x, 1) T.eq(e.y, 2)
    s:setClipRect({ 1, 2, 3, 4 })
    S.setClipRectsInRange({ 0, 0, 10, 10 }, 0, 5)
    S.clearClipRectsInRange(0, 5)
    s:setCollisionsEnabled(true)
    S.removeAll()
    s:add()
    x = s:moveWithCollisions({ 150, 100 })
    T.eq(x, 150)
end)

