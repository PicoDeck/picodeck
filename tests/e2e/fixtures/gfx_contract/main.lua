-- Counts `color` in a box.
local function count(x, y, w, h, color)
    local n = 0
    for py = y, y + h - 1 do
        for px = x, x + w - 1 do
            if D.getPixel(px, py) == color then n = n + 1 end
        end
    end
    return n
end

T.case("optional colours accept an explicit nil", function()
    D.clear(nil)
    G.clear(nil)
    T.ok(D.drawText(1, 1, "x", WHITE, nil) > 0)
    local f = G.font.new("6x8")
    T.ok(f:drawText(1, 1, "x", WHITE, nil) > 0)
    f:drawTextAligned(1, 1, "x", 0, WHITE, nil)
    f:drawTextInRect(1, 1, 50, 20, "x", nil, nil, nil)
    f:drawTextInRect(1, 1, 50, 20, "x", 0, WHITE, nil)
end)

T.case("font: false is a transparent background", function()
    fresh(BLUE)
    local f = G.font.new("6x8")
    T.eq(f:drawText(10, 10, "X", WHITE, false), 6)
    T.ok(count(10, 10, 6, 8, WHITE) > 0, "glyph drawn")
    T.ok(count(10, 10, 6, 8, BLUE) > 0, "background kept")
    D.clear(BLUE)
    f:drawTextAligned(20, 10, "X", 2, WHITE, false)
    T.ok(count(14, 10, 6, 8, WHITE) > 0, "aligned glyph drawn")
    T.ok(count(14, 10, 6, 8, BLUE) > 0, "aligned background kept")
    D.clear(BLUE)
    f:drawTextInRect(10, 10, 50, 20, "X", 0, WHITE, false)
    T.ok(count(10, 10, 6, 8, WHITE) > 0, "wrapped glyph drawn")
    T.ok(count(10, 10, 6, 8, BLUE) > 0, "wrapped background kept")
end)

