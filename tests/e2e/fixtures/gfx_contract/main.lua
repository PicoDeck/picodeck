-- A 2x2 24-bit BMP, written out so the case needs no asset.
local function tiny_bmp()
    local row = string.char(0, 0, 255, 0, 255, 0, 0, 0)
    local px = row .. row
    return "BM" .. string.pack("<I4I2I2I4", 54 + #px, 0, 0, 54)
        .. string.pack("<I4i4i4I2I2I4I4i4i4I4I4", 40, 2, 2, 1, 24, 0, #px, 0, 0, 0, 0)
        .. px
end

T.case("loadFromBuffer: len limits a string as it does a handle", function()
    local raw = tiny_bmp()
    local img = G.image.loadFromBuffer(raw)
    T.eq(img:getPixel(0, 0), RED)
    img = G.image.loadFromBuffer(raw, #raw)
    T.eq(img:getPixel(1, 0), GREEN)
    local ok, err = pcall(G.image.loadFromBuffer, raw, 8)
    T.eq(ok, false)
    T.ok(tostring(err):find("too small", 1, true), err)
    ok, err = pcall(G.image.loadFromBuffer, raw, #raw + 1)
    T.eq(ok, false)
    T.ok(tostring(err):find("exceeds", 1, true), err)
    -- Cut short of its pixels: the decoder must not read past len.
    ok = pcall(G.image.loadFromBuffer, raw, 60)
    T.eq(ok, false)
end)

