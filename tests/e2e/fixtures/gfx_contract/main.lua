-- ── Collisions ───────────────────────────────────────────────────────────────

local function mover_and_wall(wall_x, wall_w)
    fresh()
    local m = S.new(solid(10, 10, RED))
    m:setCollisionsEnabled(true)
    m:add()
    local w = S.addEmptyCollisionSprite(wall_x, 0, wall_w, 10)
    return m, w
end

T.case("moveWithCollisions: a fast mover does not pass through a thin wall", function()
    local m, w = mover_and_wall(50, 4)
    local x, y, hits = m:moveWithCollisions(100, 0)
    T.eq(x, 40)
    T.eq(y, 0)
    T.eq(#hits, 1)
    T.eq(hits[1].other, w)
    T.eq(hits[1].sprite, m)
    T.eq(hits[1].type, 1)
    T.eq(hits[1].normal.x, -1)
    T.eq(hits[1].normal.y, 0)
    T.eq(hits[1].touch.x, 40)
    T.eq(hits[1].touch.y, 0)
    T.eq(m.x, 40)
end)

T.case("moveWithCollisions: the sweep covers moves longer than the screen", function()
    local m = mover_and_wall(500, 4)
    local x = m:moveWithCollisions(1000, 0)
    T.eq(x, 490)
    m:moveTo(0, 20)
    x = m:moveWithCollisions(1000, 20)
    T.eq(x, 1000)
end)

