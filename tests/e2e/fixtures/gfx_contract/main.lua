-- picocalc.graphics contract: what the SDK review found the docs promising and
-- the code not doing. Runs on the simulator and, through --target hw, on the
-- device (test_gfx_contract.py). Reads the back buffer with display.getPixel, so
-- nothing here needs a flush.
local T = picocalc.sys.loadlib("picotest")
local D = picocalc.display
local G = picocalc.graphics
local S = G.sprite
local sys = picocalc.sys

local RED, GREEN, BLUE, WHITE, MAG = 0xF800, 0x07E0, 0x001F, 0xFFFF, 0xF81F

local function solid(w, h, c)
    local img = G.image.new(w, h)
    img:setPixels(string.pack("<I2", c):rep(w * h))
    return img
end

-- A w x h image of vertical bars, one colour per bar, each bar_w wide.
local function bars(bar_w, h, colors)
    local img = G.image.new(bar_w * #colors, h)
    for i, c in ipairs(colors) do
        img:setPixels(string.pack("<I2", c):rep(bar_w * h), (i - 1) * bar_w, 0, bar_w, h)
    end
    return img
end

local function fresh(bg)
    S.removeAll()
    D.clearClipRect()
    G.setTransparentColor(nil)
    D.clear(bg or 0)
end

local function near(got, want, tol, what)
    T.ok(math.abs(got - want) <= tol,
         (what or "value") .. ": got " .. tostring(got) .. " want " .. tostring(want))
end

