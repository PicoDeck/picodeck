#pragma once

// =============================================================================
// The files the firmware owns on the SD card (issue #92)
//
// The App Store (/apps/store), System Update (/apps/updater) and the shared Lua
// libraries (/system/lib) belong to the firmware: tools/card_files.py packs them
// into the image at build time (the generated g_card_bundle), and the boot writes
// them to the card, before WiFi starts and before the launcher's app scan. A card
// edit to any of them is overwritten: an app's own copy goes in /apps/.dev, a
// library's in the app's folder (require looks there first).
//
// A marker, CARD_FILES_MARKER, records the bundle last written and its paths:
//
//   picodeck-card-files 1
//   id <64 lowercase hex: the bundle's SHA-256, from the build>
//   /apps/store/app.json
//   ...
//
// With the marker's id equal to the bundle's, only a missing file, or one whose
// size differs, is written again. With another id, no marker or one that does
// not parse: every file is written, each marker path the new bundle no longer
// ships is deleted (only inside the bundle's roots), and the marker is written
// last, only if all of that worked, so a failed boot is retried by the next.
// Every write is sd_atomic_write: a power cut never leaves a file half-written.
// Nothing here stops the boot.
// =============================================================================

#include <stdbool.h>
#include <stdint.h>

#define CARD_FILES_MARKER "/system/firmware_files.txt"
#define CARD_FILES_PATH_MAX 150  // tools/card_files.py MAX_PATH

typedef struct {
    const char    *path;  // card path, e.g. "/apps/store/main.lua"
    const uint8_t *data;
    uint32_t       len;
} card_file_t;

typedef struct {
    const char        *id;     // 64 lowercase hex chars
    const card_file_t *files;  // sorted by path
    int                count;
    const char *const *roots;  // "/apps/store/", ...: what the firmware owns
    int                nroots;
} card_bundle_t;

typedef struct {
    int      written;    // files written this run
    int      deleted;    // stale files removed
    int      failed;     // writes or deletes that failed
    uint32_t bytes;      // bytes written
    char     error[96];  // the first failure, e.g. "write /apps/store/main.lua"
} card_files_result_t;

// Bring the card in line with the bundle. True when nothing failed. Core 0,
// thread context; the caller runs it on the OS stack (main.c).
bool card_files_sync(const card_bundle_t *b, card_files_result_t *res);

// The firmware's bundle (generated by tools/card_files.py; firmware build only).
extern const card_bundle_t g_card_bundle;
